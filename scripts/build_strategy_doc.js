// ---------- primitives ----------
// "**bold**" spans inside a string become bold runs
function runs(text, o = {}) {
  return String(text).split(/(\*\*[^*]+\*\*)/).filter(Boolean).map((s) => {
    const b = s.startsWith("**");
    const t = b ? s.slice(2, -2) : s;
    const bold = b || !!o.bold;
    const size = o.size || 22;
    return new TextRun({ text: t, font: FONT, rightToLeft: true, bold, boldComplexScript: bold, size, sizeComplexScript: size, color: o.color || K.dk });
  });
}
const P = (text, o = {}) => new Paragraph({
  bidirectional: true, alignment: o.center ? AlignmentType.CENTER : AlignmentType.BOTH,
  spacing: { after: o.after ?? 120, before: o.before ?? 0, line: 300 }, children: runs(text, o),
  shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill, color: "auto" } : undefined,
  border: o.box ? { right: { style: BorderStyle.SINGLE, size: 24, color: o.box, space: 8 } } : undefined,
  indent: o.box ? { start: 120, end: 120 } : undefined,
});
const H = (level, text) => new Paragraph({ heading: level, bidirectional: true, children: runs(text) });
const Bul = (text, lvl = 0) => new Paragraph({ bidirectional: true, alignment: AlignmentType.BOTH, numbering: { reference: "bul", level: lvl }, spacing: { after: 60, line: 290 }, children: runs(text) });
let numInst = 0;
const numbered = (items) => { const inst = ++numInst; return items.map((t) => new Paragraph({ bidirectional: true, alignment: AlignmentType.BOTH, numbering: { reference: "num", level: 0, instance: inst }, spacing: { after: 60, line: 290 }, children: runs(t) })); };
const Note = (text, color = K.gold) => P(text, { fill: "FBF6EC", box: color, after: 160 });
const Key = (text) => P(text, { fill: K.light, box: K.g, after: 160 });
const brk = () => new Paragraph({ children: [new PageBreak()] });

const border = { style: BorderStyle.SINGLE, size: 4, color: K.line };
const borders = { top: border, bottom: border, left: border, right: border };
function table(head, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const ws = widths.map((w) => Math.round((w / total) * W));
  ws[ws.length - 1] += W - ws.reduce((a, b) => a + b, 0);
  const cell = (t, i, isHead, zebra) => new TableCell({
    width: { size: ws[i], type: WidthType.DXA }, borders,
    shading: { type: ShadingType.CLEAR, color: "auto", fill: isHead ? K.g : zebra ? "F7FAF8" : "FFFFFF" },
    margins: { top: 70, bottom: 70, left: 100, right: 100 },
    children: String(t).split("\n").map((line) => new Paragraph({ bidirectional: true, spacing: { after: 20 }, children: runs(line, { size: 19, bold: isHead, color: isHead ? "FFFFFF" : K.dk }) })),
  });
  return new Table({
    width: { size: W, type: WidthType.DXA }, columnWidths: ws, visuallyRightToLeft: true,
    rows: [
      new TableRow({ tableHeader: true, children: head.map((t, i) => cell(t, i, true)) }),
      ...rows.map((r, ri) => new TableRow({ children: r.map((t, i) => cell(t, i, false, ri % 2 === 1)) })),
    ],
  });
}
const gap = () => new Paragraph({ spacing: { after: 120 }, children: [] });

// ---------- shared content blocks ----------
function deptBlock(d) {
  const out = [];
  out.push(H(HeadingLevel.HEADING_2, "التعريف"), P(d.def));
  out.push(H(HeadingLevel.HEADING_2, "الرسالة"), Key(d.mission));
  if (d.pre) out.push(...d.pre);
  out.push(H(HeadingLevel.HEADING_2, "الأقسام"));
  out.push(table(["القسم", "المسؤوليات الرئيسية"], d.sections, [3, 7]), gap());
  out.push(H(HeadingLevel.HEADING_2, "الأهداف ومؤشرات الأداء"));
  out.push(table(["#", "الهدف", "مؤشرات الأداء"], d.goals.map((g, i) => [String(i + 1), g[0], g[1]]), [0.6, 4, 5.4]), gap());
  if (d.mid) out.push(...d.mid);
  out.push(H(HeadingLevel.HEADING_2, "المبادرات (2026–2030)"));
  out.push(table(["المرحلة", "المبادرات"], d.initiatives, [2.4, 7.6]), gap());
  out.push(H(HeadingLevel.HEADING_2, "المهام والاختصاصات"));
  const inst = ++numInst; // one running sequence across all task groups
  d.tasks.forEach(([grp, items]) => {
    out.push(H(HeadingLevel.HEADING_3, grp));
    items.forEach((t) => out.push(new Paragraph({ bidirectional: true, alignment: AlignmentType.BOTH, numbering: { reference: "num", level: 0, instance: inst }, spacing: { after: 60, line: 290 }, children: runs(t) })));
  });
  if (d.post) out.push(...d.post);
  out.push(H(HeadingLevel.HEADING_2, "تجارب ملهمة"));
  out.push(table(["النطاق", "التجربة", "الدرس المستفاد"], d.cases, [1.6, 4.4, 4]), gap());
  return out;
}

